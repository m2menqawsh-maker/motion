# ── 2) MCP_INDEX ──────────────────────────────────
out, servers = ["| Server | Tool | Signature |", "|---|---|---|"], 0
for srv in sorted((DST / ".agents/plugins/super-video-maker-plugin/tools/mcp-servers").iterdir()):
    if not srv.is_dir(): continue
    found = []
    for py in sorted(srv.rglob("*.py")):
        if any(p.startswith(".venv") or p == "site-packages" or p == "__pycache__" for p in py.parts):
            continue
        src = py.read_text(encoding="utf-8")
        for m in re.finditer(r"@\w+\.tool\(\)\s*\n\s*(?:async\s+)?def\s+(\w+)\s*\(([^)]*)\)", src):
            found.append((m.group(1), re.sub(r"\s+", " ", m.group(2).strip())))
    for js in sorted(srv.glob("*.js")) + sorted(srv.glob("*.ts")):
        if any(p == "node_modules" for p in js.parts):
            continue
        src = js.read_text(encoding="utf-8")
        for m in re.finditer(r"name:\s*['\"]([a-zA-Z0-9_-]+)['\"](?:.*?properties:\s*\{(.*?)\})?", src, re.S):
            tool_name = m.group(1)
            if tool_name == srv.name:
                continue
            props = ""
            if m.group(2):
                prop_names = re.findall(r"(\w+):\s*\{", m.group(2))
                props = ", ".join(prop_names)
            found.append((tool_name, props))
    if found:
        servers += 1
        out += [f"| `{srv.name}` | `{n}` | `({a})` |" for n, a in found]


(OUT / "MCP_INDEX.md").write_text(hdr("MCP_INDEX — Real MCP Tools", "tools/mcp-servers/*")
    + f"**Servers: {servers}**\n\n" + "\n".join(out) + "\n", encoding="utf-8")
print(f"MCP_INDEX: {servers}")

