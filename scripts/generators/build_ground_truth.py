# ── 6) CINEMATIC_INDEX ────────────────────────────
def cin_family(rel):
    rel = rel.lower()
    if rel.startswith("engine/audio"): return "Audio & Sync"
    if rel.startswith("engine/camera") or rel.startswith("engine/choreography"): return "Camera & Choreography"
    if rel.startswith("engine/cursor"): return "Cursor"
    if rel.startswith("engine/layout"): return "Layout & Zones"
    if rel.startswith("engine/ui-state"): return "UI State"
    if rel.startswith("primitives/app-ui"): return "App UI Mocks"
    if rel.startswith("primitives"): return "Primitives"
    if rel.startswith("scenes"): return "Scenes"
    return "Core"

lines, n = ["| File | Exports | Props (First 12) | Family |", "|---|---|---|---|"], 0
ce = DST / "remotion-app/src/engine"
if ce.exists():
    for f in sorted(list(ce.rglob("*.tsx")) + list(ce.rglob("*.ts"))):
        if f.name == "index.ts": continue
        src = f.read_text(encoding="utf-8")
        exp = re.findall(r"export\s+(?:const|function|class)\s+([A-Za-z_$][\w$]*)", src)
        exp += re.findall(r"export\s+(?:type|interface)\s+([A-Za-z_$][\w$]*)", src)
        mdef = re.search(r"export\s+default\s+([A-Za-z_$][\w$]*)", src)
        if mdef: exp.append(mdef.group(1) + " (default)")
        if not exp: continue
        props = []
        mpr = re.search(r"(?:type|interface)\s+\w*Props\w*\s*=\s*\{(.*?)\n\}", src, re.S)
        if mpr: props = re.findall(r"([A-Za-z_$][\w$]*)\s*[?]?:", mpr.group(1))
        n += 1
        rel = f.relative_to(ce).as_posix()
        lines.append(f"| `{rel}` | {', '.join(sorted(set(exp)))} | {', '.join(props[:12]) or '—'} | {cin_family(rel)} |")
