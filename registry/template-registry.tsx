/**
 * Authoritative Canonical Registry derived directly from single truth: template-registry-data.json
 */
export const CANONICAL_TEMPLATE_REGISTRY: Record<string, TemplateEntry> = {};

/**
 * Authoritative Alias Dictionary derived directly from single truth: template-registry-data.json
 */
export const TEMPLATE_ALIASES: Record<string, string> = {};

import { resolveTemplateSchemas } from "../contracts/template-schemas";

for (const [id, tpl] of Object.entries((registryMetadata as any).templates)) {
  const t = tpl as any;
  const comp = COMPONENT_BINDINGS[t.component_name];
  if (!comp) {
    throw new Error(`Template component binding missing for '${t.canonical_id}' (${t.component_name})`);
  }
  const schemas = resolveTemplateSchemas(t.canonical_id, t.schema || {}, t.defaults || {});
  CANONICAL_TEMPLATE_REGISTRY[id] = {
    id: t.canonical_id,
    label: t.label,
    description: t.description,
    category: t.category,
    component: comp,
    defaultDurationFrames: t.default_duration_frames,
    schema: t.schema || {},
    defaults: t.defaults || {},
    contentSchema: schemas.contentSchema,
    propsSchema: schemas.propsSchema,
    surfaceSchema: schemas.surfaceSchema,
  };
  if (Array.isArray(t.aliases)) {
    for (const alias of t.aliases) {
      TEMPLATE_ALIASES[alias] = t.canonical_id;
    }
  }
}

/**
 * Proxied registry that transparently resolves ground-truth names,
 * component stems, and canonical IDs without polluting enumerable keys or Object.values().
 */
export const TEMPLATE_REGISTRY: Record<string, TemplateEntry> = new Proxy(CANONICAL_TEMPLATE_REGISTRY, {
  get(target, prop, receiver) {
    if (typeof prop === "string" && !(prop in target)) {
      const canonicalId = TEMPLATE_ALIASES[prop];
      if (canonicalId && canonicalId in target) {
        return target[canonicalId];
      }
    }
    return Reflect.get(target, prop, receiver);
  },
  has(target, prop) {
    if (typeof prop === "string" && prop in TEMPLATE_ALIASES) {
      const canonicalId = TEMPLATE_ALIASES[prop];
      if (canonicalId && canonicalId in target) {
        return true;
      }
    }
    return Reflect.has(target, prop);
  }
});

/**
 * Resolves a template entry by canonical ID, ground-truth name, or component stem.
 * Fails closed (returns undefined) for unknown template names, metadata names, or malformed strings.
 */
export function getRegistryEntry(templateName: string): TemplateEntry | undefined {
  if (!templateName || typeof templateName !== "string") return undefined;
  if (templateName.trim() !== templateName) return undefined;
  return TEMPLATE_REGISTRY[templateName];
}
