def cin_family(rel):
    rel = rel.lower()
    if rel.startswith("engine/audio"): return "Audio & Sync"
    if rel.startswith("engine/camera") or rel.startswith("engine/choreography"): return "Camera & Choreography"
    if rel.startswith("engine/cursor"): return "Cursor"
    if rel.startswith("engine/layout"): return "Layout & Zones"
    if rel.startswith("engine/ui-state"): return "UI State"
    if rel.startswith("primitives/app-ui"): return "App UI Mocks"
    if rel.startswith("primitives"): return "Primitives"
    if rel.startswith("scenes"): return "Scenes"
    return "Core"

