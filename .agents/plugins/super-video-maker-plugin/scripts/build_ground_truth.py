def fam_of(n):
    n = n.lower()
    if n.startswith("logo-") or n in ("lower-third", "subscribe-reminder"): return "Branding & Logos"
    if any(k in n for k in ("chart", "stat", "progress", "counter", "comparison")): return "Data & Stats"
    if any(k in n for k in ("transition", "wipe", "dissolve", "whip", "morph", "iris", "blinds", "pixel", "fade", "zoom-through", "clock")): return "Transitions"
    if any(k in n for k in ("noise", "film", "bokeh", "gradient", "grid", "geometric", "liquid", "matrix", "starfield", "sound-wave", "particle", "camera-shake", "vignette")): return "VFX & Overlays"
    if any(k in n for k in ("picture", "card", "carousel", "gallery", "photo", "polaroid", "stack", "notification", "parallax", "zoom-reveal", "split", "masonry")): return "Containers & Cards"
    if any(k in n for k in ("countdown", "end-card", "ken-burns", "letterbox", "spotlight", "credits")): return "CTA & Engagement"
    if any(k in n for k in ("text", "title", "quote", "typewriter", "glitch", "bubble", "popping", "bounce", "pulsing", "highlight", "list", "chapter")): return "Typography & Captions"
    return "Unclassified"

