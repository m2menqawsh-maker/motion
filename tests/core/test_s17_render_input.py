def test_s17_case_e_unresolved_media_reference_fails_closed(tmp_path):
    """Case E: Media reference in blueprint not in media_map fails closed."""
    proj_dir = tmp_path / "prj_unresolved_05"
    create_minimal_valid_project(proj_dir, "prj_unresolved_05")
    # media_map has ast_img_1, but blueprint has ast_img_999
    bp = json.loads((proj_dir / "05_blueprint.json").read_text(encoding="utf-8"))
    bp["scenes"][0]["media_refs"] = ["ast_img_999"]
    (proj_dir / "05_blueprint.json").write_text(json.dumps(bp), encoding="utf-8")

    with pytest.raises(RenderInputValidationError) as exc_info:
        build_render_input(proj_dir, workspace_root=ROOT, verify_files_on_disk=False)

    assert "Unresolved media references" in str(exc_info.value)


