def create_minimal_valid_project(proj_dir: Path, project_id: str):
    """Scaffolds a valid minimal project directory for testing."""
    proj_dir.mkdir(parents=True, exist_ok=True)
    
    # 1. 05_blueprint.json
    bp = {
        "blueprint_version": "2.0.0",
        "project_id": project_id,
        "fps": 30,
        "aspect_ratio": "16:9",
        "scenes": [
            {
                "scene_id": "scene_01",
                "template": "HeroDeviceAssembleWrapper",
                "startFrame": 0,
                "durationFrames": 60,
                "surface": {},
                "media_refs": ["ast_img_1"],
                "content": {
                    "text": "Hello World"
                }
            }
        ]
    }
    (proj_dir / "05_blueprint.json").write_text(json.dumps(bp, indent=2), encoding="utf-8")

    # 2. media_map.json
    media_map = {
        "ast_img_1": f"projects/{project_id}/test.png"
    }
    (proj_dir / "media_map.json").write_text(json.dumps(media_map, indent=2), encoding="utf-8")

    # 3. brand.json
    brand = {
        "brandName": "Test Brand",
        "colors": {
            "primary": "#FF0000",
            "accent": "#00FF00",
            "background": "#000000",
            "text": "#FFFFFF"
        },
        "fonts": {
            "display": "Cairo",
            "body": "Cairo"
        }
    }
    (proj_dir / "brand.json").write_text(json.dumps(brand, indent=2), encoding="utf-8")

    # 4. project.json
    project_meta = {
        "title": "Test Title",
        "fps": 30,
        "project_id": project_id
    }
    (proj_dir / "project.json").write_text(json.dumps(project_meta, indent=2), encoding="utf-8")

    # 5. overrides.json
    overrides = {
        "scenes": {
            "scene_01": {
                "props": {"text": "Overridden Text"}
            }
        }
    }
    (proj_dir / "overrides.json").write_text(json.dumps(overrides, indent=2), encoding="utf-8")


def test_s17_case_a_semantic_parity_across_consumers(tmp_path):
    """Case A: Single authority produces identical payload for all execution environments."""
    proj_dir = tmp_path / "prj_parity_01"
    create_minimal_valid_project(proj_dir, "prj_parity_01")

    envelope1 = build_render_input(proj_dir, workspace_root=ROOT, verify_files_on_disk=False, write_to_disk=False)
    envelope2 = build_render_input(proj_dir, workspace_root=ROOT, verify_files_on_disk=False, write_to_disk=True)

    props_file = get_render_props_path(proj_dir, workspace_root=ROOT)
    assert props_file.is_file()
    disk_envelope = json.loads(props_file.read_text(encoding="utf-8"))

    assert envelope1 == envelope2 == disk_envelope
    assert "projectData" in envelope1
    pdata = envelope1["projectData"]
    assert pdata["project"]["project_id"] == "prj_parity_01"
    assert pdata["blueprint"]["project_id"] == "prj_parity_01"
    assert pdata["brand"]["brandName"] == "Test Brand"
    assert "ast_img_1" in pdata["media_map"]


def test_s17_case_b_deterministic_output(tmp_path):
    """Case B: Output is byte-for-byte deterministic across multiple runs."""
    proj_dir = tmp_path / "prj_det_02"
    create_minimal_valid_project(proj_dir, "prj_det_02")

    build_render_input(proj_dir, workspace_root=ROOT, verify_files_on_disk=False, write_to_disk=True)
    props_path = get_render_props_path(proj_dir)
    bytes1 = props_path.read_bytes()

    build_render_input(proj_dir, workspace_root=ROOT, verify_files_on_disk=False, write_to_disk=True)
    bytes2 = props_path.read_bytes()

    assert bytes1 == bytes2


def test_s17_case_c_missing_blueprint_fails_closed(tmp_path):
    """Case C: Missing 05_blueprint.json raises RenderInputMissingArtifactError."""
    proj_dir = tmp_path / "prj_no_bp_03"
    create_minimal_valid_project(proj_dir, "prj_no_bp_03")
    (proj_dir / "05_blueprint.json").unlink()

