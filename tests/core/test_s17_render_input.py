def test_s17_case_k_cross_language_parse_render_input_roundtrip(tmp_path):
    """
    Case K: The envelope generated by build_render_input must pass
    parseRenderInput() in TypeScript without errors.
    """
    import os
    proj_dir = tmp_path / "prj_ts_roundtrip_11"
    create_minimal_valid_project(proj_dir, "prj_ts_roundtrip_11")

    envelope = build_render_input(proj_dir, workspace_root=ROOT, verify_files_on_disk=False, write_to_disk=True)
    props_file = get_render_props_path(proj_dir)

    env = os.environ.copy()
    env["LIVE_RENDER_PROPS_PATH"] = str(props_file.resolve())

    res = subprocess.run(
        ["npx", "vitest", "run", "tests/remotion/s17_render_input_parity.test.ts"],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=env,
    )
    assert res.returncode == 0, f"TypeScript parseRenderInput failed:\nSTDOUT: {res.stdout}\nSTDERR: {res.stderr}"
    assert "passed" in res.stdout
